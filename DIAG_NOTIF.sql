USE [MuhlePROD];
SET NOCOUNT ON;

PRINT '=== 1. OBJETOS ===';
SELECT LEFT(name, 40) AS NOMBRE, type_desc, CONVERT(VARCHAR(16), modify_date, 120) AS MODIFICADO
FROM sys.objects WHERE name IN ('VCT_GESTIONES','VCT_ACCIONES','VCT_GESTIONES_PARTICIPANTES','VCT_ACCIONES_PARTICIPANTES','VCT_NOTIFICACIONES',
                                'VCT_NOTIF_GENERAR','VCT_NOTIF_RENDER','VCT_NOTIF_ACCION','VCT_GET_HEADER','VCT_PROYECTOS_VISITAS_REGISTRO')
ORDER BY name;
SELECT LEFT(name, 40) AS SINONIMO, LEFT(base_object_name, 80) AS BASE FROM sys.synonyms WHERE name LIKE 'VCT_GESTION%';

PRINT '=== 2. NOTIFICACIONES POR TIPO ===';
SELECT TIPO, COUNT(*) AS N, SUM(CASE WHEN ID_PROYECTO IS NULL THEN 1 ELSE 0 END) AS SIN_PROYECTO, CONVERT(VARCHAR(16), MAX(FECHA), 120) AS ULTIMA
FROM dbo.VCT_NOTIFICACIONES WITH(NOLOCK) GROUP BY TIPO ORDER BY TIPO;

DECLARE @NAME SYSNAME, @D NVARCHAR(MAX), @TOTAL INT, @P INT, @E INT, @LINE NVARCHAR(MAX);
DECLARE c CURSOR LOCAL FAST_FORWARD FOR SELECT N FROM (VALUES ('dbo.VCT_NOTIF_GENERAR'), ('dbo.VCT_NOTIF_RENDER')) X(N);
OPEN c; FETCH NEXT FROM c INTO @NAME;
WHILE @@FETCH_STATUS = 0
BEGIN
    PRINT '';
    PRINT '=== DEFINICION ' + @NAME + ' ===';
    SET @D = OBJECT_DEFINITION(OBJECT_ID(@NAME));
    IF @D IS NULL PRINT '(no existe)';
    ELSE
    BEGIN
        SET @TOTAL = DATALENGTH(@D) / 2; SET @P = 1;
        WHILE @P <= @TOTAL
        BEGIN
            SET @E = CHARINDEX(NCHAR(10), @D, @P);
            IF @E = 0 SET @E = @TOTAL + 1;
            SET @LINE = SUBSTRING(@D, @P, @E - @P);
            IF DATALENGTH(@LINE) > 0 AND RIGHT(@LINE, 1) = NCHAR(13) SET @LINE = SUBSTRING(@LINE, 1, (DATALENGTH(@LINE) / 2) - 1);
            WHILE (DATALENGTH(@LINE) / 2) > 4000 BEGIN PRINT SUBSTRING(@LINE, 1, 4000); SET @LINE = SUBSTRING(@LINE, 4001, 1000000); END;
            PRINT @LINE;
            SET @P = @E + 1;
        END;
    END;
    FETCH NEXT FROM c INTO @NAME;
END;
CLOSE c; DEALLOCATE c;
