/* DIAG_PASO2_ASIGNAR - solo lectura. Proyecto (1347). Pasar el resultado de las 7 grillas. */
DECLARE @P INT;
SELECT @P = ID FROM dbo.VCT_PROYECTOS WITH(NOLOCK) WHERE CODIGO = '1347' OR ID = 1347;

/* 1. version del SP de asignacion instalada */
SELECT CASE WHEN OBJECT_DEFINITION(OBJECT_ID('dbo.VCT_PROYECTO_ASIGNAR_CONSULTOR')) LIKE '%V3: email obligatorio%' THEN 'V3 OK' ELSE 'NO ES V3' END AS SP_ASIGNAR,
       CASE WHEN OBJECT_DEFINITION(OBJECT_ID('dbo.VCT_MAIN_PROYECTO_V360')) LIKE '%pv_asignar_cons%' THEN 'V360 OK' ELSE 'V360 VIEJO' END AS SP_V360, @P AS ID_PROYECTO;

/* 2. roles */
SELECT ID, CODIGO, DESCRIPCION, TIPO_MIEMBRO FROM dbo.VCT_PRM_PROYECTOS_ROLES WITH(NOLOCK) ORDER BY ID;

/* 3. equipo del proyecto */
SELECT EQ.ID, EQ.TIPO_MIEMBRO, EQ.ID_EMPLEADO, EQ.ID_CONSULTOR, EQ.ID_ROL, R.CODIGO AS ROL, EQ.PRINCIPAL, EQ.ESTADO, EQ.FECHA_ALTA, EQ.USUARIO_ALTA,
       (SELECT TOP 1 M.EMAIL FROM dbo.VCT_EMAILS M WITH(NOLOCK) WHERE M.TIPO_ENTIDAD = 'CONSULTOR' AND M.ID_ENTIDAD = EQ.ID_CONSULTOR AND M.PRINCIPAL = 'SI') AS EMAIL_CONS
FROM dbo.VCT_PROYECTOS_EQUIPO EQ WITH(NOLOCK)
LEFT JOIN dbo.VCT_PRM_PROYECTOS_ROLES R WITH(NOLOCK) ON R.ID = EQ.ID_ROL
WHERE EQ.ID_PROYECTO = @P ORDER BY EQ.ID;

/* 4. acciones del proyecto */
SELECT A.ID, A.ID_SUBTIPO, ST.CODIGO AS SUBTIPO, A.ID_ESTADO, E.CODIGO AS ESTADO, A.ID_REGLA_ORIGEN, A.TITULO, A.FECHA_VENCIMIENTO, A.FECHA_CIERRE
FROM dbo.VCT_ACCIONES A WITH(NOLOCK)
LEFT JOIN dbo.VCT_PRM_ACCIONES_SUBTIPOS ST WITH(NOLOCK) ON ST.ID = A.ID_SUBTIPO
LEFT JOIN dbo.VCT_PRM_ACCIONES_ESTADOS E WITH(NOLOCK) ON E.ID = A.ID_ESTADO
WHERE A.ID_PROYECTO = @P ORDER BY A.ID;

/* 5. historial de esas acciones */
SELECT H.ID_ACCION, H.ACCION, H.DESCRIPCION, H.FECHA, H.USUARIO
FROM dbo.VCT_ACCIONES_HISTORIAL H WITH(NOLOCK)
WHERE H.ID_ACCION IN (SELECT ID FROM dbo.VCT_ACCIONES WITH(NOLOCK) WHERE ID_PROYECTO = @P)
ORDER BY H.FECHA;

/* 6. reglas del evento */
SELECT ID, CODIGO, CODIGO_EVENTO, DESTINATARIO_ROL, DIAS_VENCIMIENTO, GENERA_EMAIL, ID_EMAIL_TEMPLATE, ACTIVO
FROM dbo.VCT_PRM_ACCIONES_REGLAS WITH(NOLOCK) WHERE CODIGO_EVENTO IN ('CONSULTORES_ASIGNADOS','PROYECTO_INICIADO');

/* 7. ultimos mails enviados por Database Mail */
SELECT TOP 10 mailitem_id, recipients, copy_recipients, subject, sent_status, send_request_date
FROM msdb.dbo.sysmail_allitems ORDER BY mailitem_id DESC;
