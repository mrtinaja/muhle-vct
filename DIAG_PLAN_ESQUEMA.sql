/* DIAG_PLAN_ESQUEMA - solo lectura. Para armar la pestania Parte logistico (Plan Estrategico)
   sobre las tablas existentes. Pasar el resultado de todas las grillas. */
USE [MuhlePROD];
SET NOCOUNT ON;

/* 1. columnas de plan, items y acciones */
SELECT C.TABLE_NAME, C.ORDINAL_POSITION, C.COLUMN_NAME, C.DATA_TYPE, C.CHARACTER_MAXIMUM_LENGTH AS LARGO, C.IS_NULLABLE,
       COLUMNPROPERTY(OBJECT_ID('dbo.' + C.TABLE_NAME), C.COLUMN_NAME, 'IsIdentity') AS ES_IDENTITY
FROM INFORMATION_SCHEMA.COLUMNS C
WHERE C.TABLE_SCHEMA = 'dbo' AND C.TABLE_NAME IN ('VCT_PROYECTOS_PLANES','VCT_PROYECTOS_PLAN_ITEMS','VCT_ACCIONES')
ORDER BY C.TABLE_NAME, C.ORDINAL_POSITION;

/* 2. restricciones CHECK y claves foraneas de esas tablas */
SELECT OBJECT_NAME(parent_object_id) AS TABLA, name AS RESTRICCION, definition AS DEFINICION
FROM sys.check_constraints
WHERE parent_object_id IN (OBJECT_ID('dbo.VCT_PROYECTOS_PLANES'), OBJECT_ID('dbo.VCT_PROYECTOS_PLAN_ITEMS'), OBJECT_ID('dbo.VCT_ACCIONES'));
SELECT OBJECT_NAME(F.parent_object_id) AS TABLA, F.name AS FK, COL_NAME(FC.parent_object_id, FC.parent_column_id) AS COLUMNA,
       OBJECT_NAME(F.referenced_object_id) AS REFERENCIA
FROM sys.foreign_keys F INNER JOIN sys.foreign_key_columns FC ON FC.constraint_object_id = F.object_id
WHERE F.parent_object_id IN (OBJECT_ID('dbo.VCT_PROYECTOS_PLANES'), OBJECT_ID('dbo.VCT_PROYECTOS_PLAN_ITEMS'));

/* 3. planes existentes y cantidad de items */
SELECT P.*, (SELECT COUNT(*) FROM dbo.VCT_PROYECTOS_PLAN_ITEMS I WITH(NOLOCK) WHERE I.ID_PLAN = P.ID) AS ITEMS
FROM dbo.VCT_PROYECTOS_PLANES P WITH(NOLOCK) ORDER BY P.ID;

/* 4. muestra de items de un plan existente */
SELECT TOP 15 I.* FROM dbo.VCT_PROYECTOS_PLAN_ITEMS I WITH(NOLOCK) ORDER BY I.ID_PLAN, I.ORDEN, I.ID;

/* 5. plan base de parametria (RE-PP-007, TIPO_DETALLE PLAN): items */
SELECT D.ID AS ID_DOC, D.CODIGO, D.DESCRIPCION AS DOC, D.COMENTARIO, I.ID, I.ID_PADRE, I.CODIGO_ITEM, I.DESCRIPCION, I.GRUPO, I.ORDEN, I.OBLIGATORIO, I.ACTIVO
FROM dbo.VCT_PRM_DOCUMENTOS D WITH(NOLOCK)
INNER JOIN dbo.VCT_PRM_DOCUMENTOS_ITEMS I WITH(NOLOCK) ON I.ID_DOCUMENTO = D.ID
WHERE D.CODIGO = 'RE-PP-007'
ORDER BY D.ID, I.ORDEN, I.ID;

/* 6. proyecto 1347: tipo, servicios y acciones ligadas a plan */
SELECT P.ID, P.CODIGO, P.TIPO_PROYECTO, P.FECHA_INICIO, P.FECHA_FIN, P.FECHA_INICIO_REAL FROM dbo.VCT_PROYECTOS P WITH(NOLOCK) WHERE P.CODIGO = '1347';
SELECT PS.ID, PS.ID_SERVICIO, S.CODIGO, S.DESCRIPCION FROM dbo.VCT_PROYECTOS_SERVICIOS PS WITH(NOLOCK)
INNER JOIN dbo.VCT_PRM_SERVICIOS S WITH(NOLOCK) ON S.ID = PS.ID_SERVICIO
INNER JOIN dbo.VCT_PROYECTOS P WITH(NOLOCK) ON P.ID = PS.ID_PROYECTO AND P.CODIGO = '1347';
IF COL_LENGTH('dbo.VCT_ACCIONES', 'ID_PLAN_ITEM') IS NOT NULL
    EXEC('SELECT COUNT(*) AS ACCIONES_CON_ITEM FROM dbo.VCT_ACCIONES WITH(NOLOCK) WHERE ID_PLAN_ITEM IS NOT NULL');
ELSE SELECT 'VCT_ACCIONES no tiene ID_PLAN_ITEM' AS AVISO;

/* 7. objetos auxiliares que usaba el plan anterior */
SELECT name, type_desc FROM sys.objects WHERE name IN ('VCT_CK_VALOR','VCT_PROYECTO_PLAN_CALC','VCT_PROYECTO_AVANCE','VCT_PROYECTO_AVANCE_SYNC');
