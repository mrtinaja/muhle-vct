/* DIAG_PLAN_GRABAR_1349: por que no graban items / acciones del plan del proyecto 1349 (solo lectura).
   SSMS: Query > SQLCMD Mode, F5. */
SET NOCOUNT ON;
DECLARE @P INT;
SELECT TOP 1 @P = ID FROM dbo.VCT_PROYECTOS WITH(NOLOCK) WHERE ID = 1349 OR CODIGO = '1349' ORDER BY CASE WHEN ID = 1349 THEN 0 ELSE 1 END;

PRINT '=== 1. PROYECTO ===';
SELECT ID, CODIGO, FECHA_INICIO, FECHA_INICIO_REAL, FECHA_FIN FROM dbo.VCT_PROYECTOS WITH(NOLOCK) WHERE ID = @P;

PRINT '=== 2. PLAN E ITEMS ===';
SELECT ID, VERSION FROM dbo.VCT_PROYECTOS_PLANES WITH(NOLOCK) WHERE ID_PROYECTO = @P;
SELECT I.ID, I.ID_PADRE, LEFT(ISNULL(I.GRUPO,''), 20) AS GRUPO, LEFT(ISNULL(I.CODIGO_ITEM,''), 10) AS COD, LEFT(I.TITULO, 60) AS TITULO,
       CONVERT(VARCHAR(10), I.FECHA_INICIO, 103) AS INI, CONVERT(VARCHAR(10), I.FECHA_VENCIMIENTO, 103) AS FIN,
       I.ID_RESPONSABLE_EQUIPO AS RESP, CONVERT(VARCHAR(16), I.FECHA_UPD, 120) AS FECHA_UPD, LEFT(ISNULL(I.USUARIO_UPD,''), 30) AS USUARIO_UPD
FROM dbo.VCT_PROYECTOS_PLAN_ITEMS I WITH(NOLOCK)
INNER JOIN dbo.VCT_PROYECTOS_PLANES PL WITH(NOLOCK) ON PL.ID = I.ID_PLAN
WHERE PL.ID_PROYECTO = @P
ORDER BY I.ORDEN, I.ID;

PRINT '=== 3. ACCIONES DEL PROYECTO ===';
SELECT A.ID, A.ID_PLAN_ITEM, LEFT(ISNULL(ST.CODIGO,''), 25) AS SUBTIPO, LEFT(ISNULL(E.CODIGO,''), 15) AS ESTADO, LEFT(A.TITULO, 60) AS TITULO,
       CONVERT(VARCHAR(10), A.FECHA_INICIO, 103) AS INI, CONVERT(VARCHAR(10), A.FECHA_VENCIMIENTO, 103) AS VENCE,
       CONVERT(VARCHAR(16), A.FECHA_ALTA, 120) AS ALTA, LEFT(ISNULL(A.USUARIO_ALTA,''), 30) AS USUARIO_ALTA, CONVERT(VARCHAR(16), A.FECHA_UPD, 120) AS FECHA_UPD
FROM dbo.VCT_ACCIONES A WITH(NOLOCK)
LEFT JOIN dbo.VCT_PRM_ACCIONES_SUBTIPOS ST WITH(NOLOCK) ON ST.ID = A.ID_SUBTIPO
LEFT JOIN dbo.VCT_PRM_ACCIONES_ESTADOS E WITH(NOLOCK) ON E.ID = A.ID_ESTADO
WHERE A.ID_PROYECTO = @P
ORDER BY A.ID;

PRINT '=== 4. HISTORIAL (ultimos 40) ===';
SELECT TOP 40 H.ID_ACCION, LEFT(ISNULL(H.ACCION,''), 20) AS ACCION, LEFT(ISNULL(H.DESCRIPCION,''), 90) AS DESCRIPCION, CONVERT(VARCHAR(19), H.FECHA, 120) AS FECHA, LEFT(ISNULL(H.USUARIO,''), 30) AS USUARIO
FROM dbo.VCT_ACCIONES_HISTORIAL H WITH(NOLOCK)
INNER JOIN dbo.VCT_ACCIONES A WITH(NOLOCK) ON A.ID = H.ID_ACCION
WHERE A.ID_PROYECTO = @P
ORDER BY H.FECHA DESC;

PRINT '=== 5. BUFFER CON COMANDOS DEL PLAN SIN PROCESAR ===';
SELECT LEFT(PAR_KEY, 40) AS PAR_KEY, FLAG01, LEFT(ISNULL(TEXTO30,''), 25) AS CMD, IDSELEC02, IDSELEC03,
       LEFT(ISNULL(TEXTO11,''), 40) AS T11, LEFT(ISNULL(TEXTO12,''), 12) AS T12, LEFT(ISNULL(TEXTO13,''), 12) AS T13, LEFT(ISNULL(TEXTO14,''), 12) AS T14,
       LEFT(ISNULL(TEXTO15,''), 12) AS T15, LEFT(ISNULL(TEXTO16,''), 12) AS T16, LEFT(ISNULL(TEXTO19,''), 12) AS T19, LEFT(ISNULL(TEXTO21,''), 12) AS T21
FROM dbo.VCT_BUFFER WITH(NOLOCK)
WHERE ISNULL(TEXTO30,'') LIKE 'PV[_]%';
