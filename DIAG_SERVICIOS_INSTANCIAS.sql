/* DIAG_SERVICIOS_INSTANCIAS - solo lectura.
   Para confirmar si el modelo actual ya soporta N auditorias / N capacitaciones por proyecto,
   cada una con su plan (de auditoria / de capacitacion), items, acciones, equipo, normas y visitas.
   Pasar el resultado de todas las grillas. */
USE [MuhlePROD];
SET NOCOUNT ON;

/* 1. columnas de las tablas que cuelgan del servicio del proyecto */
SELECT C.TABLE_NAME, C.ORDINAL_POSITION, C.COLUMN_NAME, C.DATA_TYPE, C.CHARACTER_MAXIMUM_LENGTH AS LARGO, C.IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS C
WHERE C.TABLE_SCHEMA = 'dbo'
  AND C.TABLE_NAME IN ('VCT_PROYECTOS_SERVICIOS','VCT_PRM_SERVICIOS','VCT_PROYECTOS_PLANES','VCT_PROYECTOS_EQUIPO',
                       'VCT_PROYECTOS_NORMAS','VCT_PROYECTOS_VISITAS','VCT_PRM_DOCUMENTOS','VCT_PROYECTOS_DOCUMENTOS')
ORDER BY C.TABLE_NAME, C.ORDINAL_POSITION;

/* 2. claves unicas, foraneas y CHECK de esas tablas */
SELECT OBJECT_NAME(I.object_id) AS TABLA, I.name AS INDICE, I.is_unique, I.is_primary_key,
       STUFF((SELECT ', ' + COL_NAME(IC.object_id, IC.column_id) FROM sys.index_columns IC
              WHERE IC.object_id = I.object_id AND IC.index_id = I.index_id ORDER BY IC.key_ordinal FOR XML PATH('')), 1, 2, '') AS COLUMNAS
FROM sys.indexes I
WHERE I.object_id IN (OBJECT_ID('dbo.VCT_PROYECTOS_SERVICIOS'), OBJECT_ID('dbo.VCT_PROYECTOS_PLANES'), OBJECT_ID('dbo.VCT_PROYECTOS_EQUIPO'),
                      OBJECT_ID('dbo.VCT_PROYECTOS_NORMAS'))
  AND (I.is_unique = 1 OR I.is_primary_key = 1);
SELECT OBJECT_NAME(F.parent_object_id) AS TABLA, F.name AS FK, COL_NAME(FC.parent_object_id, FC.parent_column_id) AS COLUMNA,
       OBJECT_NAME(F.referenced_object_id) AS REFERENCIA
FROM sys.foreign_keys F INNER JOIN sys.foreign_key_columns FC ON FC.constraint_object_id = F.object_id
WHERE F.parent_object_id IN (OBJECT_ID('dbo.VCT_PROYECTOS_SERVICIOS'), OBJECT_ID('dbo.VCT_PROYECTOS_PLANES'), OBJECT_ID('dbo.VCT_PRM_DOCUMENTOS'))
ORDER BY 1, 2;
SELECT OBJECT_NAME(parent_object_id) AS TABLA, name, definition FROM sys.check_constraints
WHERE parent_object_id IN (OBJECT_ID('dbo.VCT_PROYECTOS_SERVICIOS'), OBJECT_ID('dbo.VCT_PROYECTOS_PLANES'), OBJECT_ID('dbo.VCT_PRM_DOCUMENTOS'));

/* 3. servicios de parametria */
SELECT * FROM dbo.VCT_PRM_SERVICIOS ORDER BY ID;

/* 4. documentos de parametria (planes base, minutas, informes...) */
SELECT D.ID, D.CODIGO, D.DESCRIPCION, D.TIPO_DETALLE, D.ACTIVO,
       (SELECT COUNT(*) FROM dbo.VCT_PRM_DOCUMENTOS_ITEMS I WITH(NOLOCK) WHERE I.ID_DOCUMENTO = D.ID) AS ITEMS
FROM dbo.VCT_PRM_DOCUMENTOS D WITH(NOLOCK) ORDER BY D.CODIGO, D.ID;

/* 5. caso Air Liquide (1281): servicios del proyecto agrupados y detalle */
SELECT PS.CODIGO, PS.DESCRIPCION, COUNT(*) AS CANTIDAD, SUM(ISNULL(S.TOTAL_HORAS_PROYECTADAS,0)) AS HORAS
FROM dbo.VCT_PROYECTOS_SERVICIOS S WITH(NOLOCK)
INNER JOIN dbo.VCT_PROYECTOS P WITH(NOLOCK) ON P.ID = S.ID_PROYECTO AND P.CODIGO = '1281'
LEFT JOIN dbo.VCT_PRM_SERVICIOS PS WITH(NOLOCK) ON PS.ID = S.ID_SERVICIO
GROUP BY PS.CODIGO, PS.DESCRIPCION;
SELECT TOP 30 S.* FROM dbo.VCT_PROYECTOS_SERVICIOS S WITH(NOLOCK)
INNER JOIN dbo.VCT_PROYECTOS P WITH(NOLOCK) ON P.ID = S.ID_PROYECTO AND P.CODIGO = '1281'
ORDER BY S.ORDEN, S.ID;

/* 6. lo que ya cuelga de cada servicio del proyecto 1281 */
SELECT S.ID AS ID_PROY_SERV, ISNULL(S.NOMBRE,'') AS NOMBRE,
       (SELECT COUNT(*) FROM dbo.VCT_PROYECTOS_EQUIPO E WITH(NOLOCK) WHERE E.ID_PROYECTO_SERVICIO = S.ID) AS EQUIPO,
       (SELECT COUNT(*) FROM dbo.VCT_PROYECTOS_NORMAS N WITH(NOLOCK) WHERE N.ID_PROYECTO_SERVICIO = S.ID) AS NORMAS,
       (SELECT COUNT(*) FROM dbo.VCT_PROYECTOS_VISITAS V WITH(NOLOCK) WHERE V.ID_PROYECTO_SERVICIO = S.ID) AS VISITAS,
       (SELECT COUNT(*) FROM dbo.VCT_PROYECTOS_PLANES L WITH(NOLOCK) WHERE L.ID_PROYECTO_SERVICIO = S.ID) AS PLANES,
       (SELECT COUNT(*) FROM dbo.VCT_ACCIONES A WITH(NOLOCK) WHERE A.ID_PROYECTO_SERVICIO = S.ID) AS ACCIONES
FROM dbo.VCT_PROYECTOS_SERVICIOS S WITH(NOLOCK)
INNER JOIN dbo.VCT_PROYECTOS P WITH(NOLOCK) ON P.ID = S.ID_PROYECTO AND P.CODIGO = '1281'
ORDER BY S.ORDEN, S.ID;

/* 7. en toda la base: proyectos con mas de una instancia del mismo servicio */
SELECT PS.CODIGO, COUNT(DISTINCT S.ID_PROYECTO) AS PROYECTOS_CON_VARIAS, MAX(X.N) AS MAX_INSTANCIAS
FROM (SELECT ID_PROYECTO, ID_SERVICIO, COUNT(*) AS N FROM dbo.VCT_PROYECTOS_SERVICIOS WITH(NOLOCK) GROUP BY ID_PROYECTO, ID_SERVICIO HAVING COUNT(*) > 1) X
INNER JOIN dbo.VCT_PROYECTOS_SERVICIOS S WITH(NOLOCK) ON S.ID_PROYECTO = X.ID_PROYECTO AND S.ID_SERVICIO = X.ID_SERVICIO
LEFT JOIN dbo.VCT_PRM_SERVICIOS PS WITH(NOLOCK) ON PS.ID = S.ID_SERVICIO
GROUP BY PS.CODIGO;
