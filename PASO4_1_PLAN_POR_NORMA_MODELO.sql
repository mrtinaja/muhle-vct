/* ========================================================================
   PASO4_1_PLAN_POR_NORMA_MODELO  (solo estructura: no toca datos)
   ------------------------------------------------------------------------
   1. VCT_PRM_DOCUMENTOS.ID_NORMA (FK a VCT_PRM_NORMAS): cada plan base
      (TIPO_DETALLE = 'PLAN') queda asociado a su norma.
   2. VCT_ACCIONES_PARTICIPANTES: responsable "Otro" con nombre libre.
        - columna NOMBRE_LIBRE VARCHAR(150) NULL
        - TIPO_ENTIDAD admite 'OTRO' (sin ID_ENTIDAD, con NOMBRE_LIBRE)
      Los CHECK existentes se reemplazan por la misma regla + OTRO.
   Correr ANTES de PASO4_2 y de PASO2_3 (el SP usa estas columnas).
   Re-ejecutable.
   ======================================================================== */
USE [MuhlePROD];
SET NOCOUNT ON;
IF OBJECT_ID('tempdb..#TRG41') IS NOT NULL DROP TABLE #TRG41;
CREATE TABLE #TRG41 (ON_ BIT);
INSERT INTO #TRG41 SELECT CASE WHEN EXISTS (SELECT 1 FROM sys.triggers WHERE name = 'TR_VCT_AUDITORIA_DDL' AND parent_class = 0 AND is_disabled = 0) THEN 1 ELSE 0 END;
IF EXISTS (SELECT 1 FROM #TRG41 WHERE ON_ = 1) DISABLE TRIGGER TR_VCT_AUDITORIA_DDL ON DATABASE;
GO

/* ---------- 1. plan base por norma ---------- */
IF COL_LENGTH('dbo.VCT_PRM_DOCUMENTOS', 'ID_NORMA') IS NULL
BEGIN
    ALTER TABLE dbo.VCT_PRM_DOCUMENTOS ADD ID_NORMA INT NULL;
    PRINT 'OK   VCT_PRM_DOCUMENTOS.ID_NORMA agregada.';
END
ELSE PRINT 'OK   VCT_PRM_DOCUMENTOS.ID_NORMA ya existia.';
GO
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_VCT_PRM_DOC_NORMA')
BEGIN
    ALTER TABLE dbo.VCT_PRM_DOCUMENTOS WITH CHECK ADD CONSTRAINT FK_VCT_PRM_DOC_NORMA FOREIGN KEY (ID_NORMA) REFERENCES dbo.VCT_PRM_NORMAS (ID);
    PRINT 'OK   FK_VCT_PRM_DOC_NORMA creada.';
END;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_VCT_PRM_DOC_NORMA' AND object_id = OBJECT_ID('dbo.VCT_PRM_DOCUMENTOS'))
BEGIN
    CREATE INDEX IX_VCT_PRM_DOC_NORMA ON dbo.VCT_PRM_DOCUMENTOS (ID_NORMA, TIPO_DETALLE, ACTIVO);
    PRINT 'OK   IX_VCT_PRM_DOC_NORMA creado.';
END;
GO

/* ---------- 2. responsable "Otro" (nombre libre) ---------- */
IF COL_LENGTH('dbo.VCT_ACCIONES_PARTICIPANTES', 'NOMBRE_LIBRE') IS NULL
BEGIN
    ALTER TABLE dbo.VCT_ACCIONES_PARTICIPANTES ADD NOMBRE_LIBRE VARCHAR(150) NULL;
    PRINT 'OK   VCT_ACCIONES_PARTICIPANTES.NOMBRE_LIBRE agregada.';
END
ELSE PRINT 'OK   VCT_ACCIONES_PARTICIPANTES.NOMBRE_LIBRE ya existia.';
GO
IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_VCT_GES_PART_ENTIDAD' AND definition NOT LIKE '%OTRO%')
    ALTER TABLE dbo.VCT_ACCIONES_PARTICIPANTES DROP CONSTRAINT CK_VCT_GES_PART_ENTIDAD;
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_VCT_GES_PART_ENTIDAD')
BEGIN
    ALTER TABLE dbo.VCT_ACCIONES_PARTICIPANTES WITH CHECK ADD CONSTRAINT CK_VCT_GES_PART_ENTIDAD
        CHECK ([TIPO_ENTIDAD] IN ('SISTEMA','PROVEEDOR','CLIENTE','CONSULTOR','EMPLEADO','OTRO'));
    PRINT 'OK   CK_VCT_GES_PART_ENTIDAD admite OTRO.';
END;
IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_VCT_GES_PART_ID' AND definition NOT LIKE '%OTRO%')
    ALTER TABLE dbo.VCT_ACCIONES_PARTICIPANTES DROP CONSTRAINT CK_VCT_GES_PART_ID;
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_VCT_GES_PART_ID')
BEGIN
    ALTER TABLE dbo.VCT_ACCIONES_PARTICIPANTES WITH CHECK ADD CONSTRAINT CK_VCT_GES_PART_ID
        CHECK (([TIPO_ENTIDAD] IN ('SISTEMA','OTRO') AND [ID_ENTIDAD] IS NULL) OR ([TIPO_ENTIDAD] NOT IN ('SISTEMA','OTRO') AND [ID_ENTIDAD] IS NOT NULL));
    PRINT 'OK   CK_VCT_GES_PART_ID: SISTEMA y OTRO sin ID.';
END;
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_VCT_GES_PART_OTRO')
BEGIN
    ALTER TABLE dbo.VCT_ACCIONES_PARTICIPANTES WITH CHECK ADD CONSTRAINT CK_VCT_GES_PART_OTRO
        CHECK ([TIPO_ENTIDAD] <> 'OTRO' OR LEN(LTRIM(RTRIM(ISNULL([NOMBRE_LIBRE],'')))) > 0);
    PRINT 'OK   CK_VCT_GES_PART_OTRO: OTRO requiere nombre.';
END;
GO

IF EXISTS (SELECT 1 FROM #TRG41 WHERE ON_ = 1) ENABLE TRIGGER TR_VCT_AUDITORIA_DDL ON DATABASE;
DROP TABLE #TRG41;
PRINT 'OK   PASO4_1 terminado.';
