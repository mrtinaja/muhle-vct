/* ========================================================================
   PASO5_1_ACCIONES_TIPIFICACION
   ------------------------------------------------------------------------
   Set de tipificacion de acciones para la carga manual (modal de accion del
   proyecto y del plan). Base: documento funcional seccion 6 + minuta.
   1. Estructura (re-ejecutable):
        VCT_PRM_ACCIONES_SUBTIPOS.CARGA_MANUAL  VARCHAR(10) NOT NULL DEFAULT 'AMBOS'
            SISTEMA  = solo lo genera el sistema (no aparece en ningun modal)
            PROYECTO = modal "Agregar accion" de la pestana Acciones
            PLAN     = modal de accion del item del plan
            AMBOS    = los dos modales
        VCT_PRM_ACCIONES_RESULTADOS.CARGA_MANUAL BIT NOT NULL DEFAULT 1
            0 = resultado que solo pone el sistema (ej. Consultor asignado)
   2. Parametria:
        - marca cada subtipo existente (por CODIGO)
        - agrega subtipos: REUNION_CLIENTE, COORDINACION_INTERNA, DOCUMENTO_REVISION,
          SEGUIMIENTO_QUINCENAL, SEGUIMIENTO_CLIENTE
        - agrega resultados: OBSERVADA, REPROGRAMADA
        - desactiva (ACTIVO = 0, no borra) los tipos sin subtipos y sin acciones:
          APROBACION, VIATICO, HONORARIO (viatico / honorario ya estan como subtipos de SOLICITUD)
   No toca acciones cargadas, permisos, vistas ni SPs.
   Correr ANTES de PASO2_3 (el SP usa CARGA_MANUAL).
   ======================================================================== */
USE [MuhlePROD];
SET NOCOUNT ON;
IF OBJECT_ID('tempdb..#TRG51') IS NOT NULL DROP TABLE #TRG51;
CREATE TABLE #TRG51 (ON_ BIT);
INSERT INTO #TRG51 SELECT CASE WHEN EXISTS (SELECT 1 FROM sys.triggers WHERE name = 'TR_VCT_AUDITORIA_DDL' AND parent_class = 0 AND is_disabled = 0) THEN 1 ELSE 0 END;
IF EXISTS (SELECT 1 FROM #TRG51 WHERE ON_ = 1) DISABLE TRIGGER TR_VCT_AUDITORIA_DDL ON DATABASE;
GO

/* ---------- 1. estructura ---------- */
IF COL_LENGTH('dbo.VCT_PRM_ACCIONES_SUBTIPOS', 'CARGA_MANUAL') IS NULL
BEGIN
    ALTER TABLE dbo.VCT_PRM_ACCIONES_SUBTIPOS ADD CARGA_MANUAL VARCHAR(10) NOT NULL
        CONSTRAINT DF_VCT_PRM_ACC_SUB_CARGA DEFAULT ('AMBOS');
    PRINT 'OK   VCT_PRM_ACCIONES_SUBTIPOS.CARGA_MANUAL agregada.';
END
ELSE PRINT 'OK   VCT_PRM_ACCIONES_SUBTIPOS.CARGA_MANUAL ya existia.';
GO
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_VCT_PRM_ACC_SUB_CARGA')
BEGIN
    ALTER TABLE dbo.VCT_PRM_ACCIONES_SUBTIPOS WITH CHECK ADD CONSTRAINT CK_VCT_PRM_ACC_SUB_CARGA
        CHECK ([CARGA_MANUAL] IN ('SISTEMA','PROYECTO','PLAN','AMBOS'));
    PRINT 'OK   CK_VCT_PRM_ACC_SUB_CARGA creada.';
END;
IF COL_LENGTH('dbo.VCT_PRM_ACCIONES_RESULTADOS', 'CARGA_MANUAL') IS NULL
BEGIN
    ALTER TABLE dbo.VCT_PRM_ACCIONES_RESULTADOS ADD CARGA_MANUAL BIT NOT NULL
        CONSTRAINT DF_VCT_PRM_ACC_RES_CARGA DEFAULT (1);
    PRINT 'OK   VCT_PRM_ACCIONES_RESULTADOS.CARGA_MANUAL agregada.';
END
ELSE PRINT 'OK   VCT_PRM_ACCIONES_RESULTADOS.CARGA_MANUAL ya existia.';
GO

/* ---------- 2. parametria ---------- */
BEGIN TRY
    BEGIN TRAN;

    /* 2.1 subtipos existentes */
    DECLARE @M TABLE (CODIGO VARCHAR(50), CARGA VARCHAR(10));
    INSERT INTO @M VALUES
        ('ASIGNACION_ANALISTA','SISTEMA'), ('ASIGNACION_CONSULTOR','SISTEMA'), ('CARGA_PLAN','SISTEMA'),
        ('CARGA_DATOS_ENTRADA','SISTEMA'), ('LANZAMIENTO','SISTEMA'), ('AVISO_VENCIMIENTO','SISTEMA'),
        ('VISITA_HISTORICA','SISTEMA'), ('PROYECTO_FINALIZADO','SISTEMA'),
        ('TRABAJO_PLAN_ITEM','PLAN'),
        ('PENDIENTE_CLIENTE','AMBOS'), ('DOCUMENTO_PENDIENTE','AMBOS'),
        ('SOLICITUD_VIATICO','PROYECTO'), ('SOLICITUD_HONORARIO','PROYECTO');
    UPDATE S SET CARGA_MANUAL = M.CARGA, FECHA_UPD = GETDATE(), USUARIO_UPD = 'PASO5_1'
    FROM dbo.VCT_PRM_ACCIONES_SUBTIPOS S INNER JOIN @M M ON M.CODIGO = S.CODIGO
    WHERE S.CARGA_MANUAL <> M.CARGA;
    PRINT 'OK   subtipos existentes marcados (' + CONVERT(VARCHAR(10), @@ROWCOUNT) + ' cambiados).';

    /* 2.2 subtipos nuevos */
    DECLARE @N TABLE (TIPO VARCHAR(50), CODIGO VARCHAR(50), DESCRIPCION VARCHAR(150), ORDEN INT, CARGA VARCHAR(10));
    INSERT INTO @N VALUES
        ('ACTIVIDAD',     'REUNION_CLIENTE',       'Reuni' + CHAR(243) + 'n con el cliente', 5, 'AMBOS'),
        ('TAREA',         'COORDINACION_INTERNA',  'Coordinaci' + CHAR(243) + 'n interna', 45, 'PROYECTO'),
        ('DOCUMENTACION', 'DOCUMENTO_REVISION',    'Revisi' + CHAR(243) + 'n / aprobaci' + CHAR(243) + 'n de documento', 81, 'AMBOS'),
        ('SEGUIMIENTO',   'SEGUIMIENTO_QUINCENAL', 'Seguimiento quincenal del proyecto', 10, 'PROYECTO'),
        ('SEGUIMIENTO',   'SEGUIMIENTO_CLIENTE',   'Contacto de seguimiento con el cliente', 20, 'PROYECTO');
    IF EXISTS (SELECT 1 FROM @N N WHERE NOT EXISTS (SELECT 1 FROM dbo.VCT_PRM_ACCIONES_TIPOS T WHERE T.CODIGO = N.TIPO))
        RAISERROR('Falta alguno de los tipos ACTIVIDAD, TAREA, DOCUMENTACION o SEGUIMIENTO.', 16, 1);
    IF COLUMNPROPERTY(OBJECT_ID('dbo.VCT_PRM_ACCIONES_SUBTIPOS'), 'ID', 'IsIdentity') = 1
        INSERT INTO dbo.VCT_PRM_ACCIONES_SUBTIPOS (ID_TIPO, CODIGO, DESCRIPCION, ORDEN, ACTIVO, CARGA_MANUAL, FECHA_ALTA, USUARIO_ALTA)
        SELECT T.ID, N.CODIGO, N.DESCRIPCION, N.ORDEN, 1, N.CARGA, GETDATE(), 'PASO5_1'
        FROM @N N INNER JOIN dbo.VCT_PRM_ACCIONES_TIPOS T ON T.CODIGO = N.TIPO
        WHERE NOT EXISTS (SELECT 1 FROM dbo.VCT_PRM_ACCIONES_SUBTIPOS S WHERE S.CODIGO = N.CODIGO);
    ELSE
        INSERT INTO dbo.VCT_PRM_ACCIONES_SUBTIPOS (ID, ID_TIPO, CODIGO, DESCRIPCION, ORDEN, ACTIVO, CARGA_MANUAL, FECHA_ALTA, USUARIO_ALTA)
        SELECT (SELECT ISNULL(MAX(ID), 0) FROM dbo.VCT_PRM_ACCIONES_SUBTIPOS) + ROW_NUMBER() OVER (ORDER BY N.ORDEN, N.CODIGO),
               T.ID, N.CODIGO, N.DESCRIPCION, N.ORDEN, 1, N.CARGA, GETDATE(), 'PASO5_1'
        FROM @N N INNER JOIN dbo.VCT_PRM_ACCIONES_TIPOS T ON T.CODIGO = N.TIPO
        WHERE NOT EXISTS (SELECT 1 FROM dbo.VCT_PRM_ACCIONES_SUBTIPOS S WHERE S.CODIGO = N.CODIGO);
    PRINT 'OK   subtipos nuevos (' + CONVERT(VARCHAR(10), @@ROWCOUNT) + ' agregados).';

    /* 2.3 resultados */
    UPDATE dbo.VCT_PRM_ACCIONES_RESULTADOS SET CARGA_MANUAL = 0, FECHA_UPD = GETDATE(), USUARIO_UPD = 'PASO5_1'
    WHERE CODIGO = 'CONSULTOR_ASIGNADO' AND CARGA_MANUAL <> 0;
    DECLARE @R TABLE (CODIGO VARCHAR(50), DESCRIPCION VARCHAR(150), ORDEN INT);
    INSERT INTO @R VALUES ('OBSERVADA', 'Observada (con correcciones)', 25), ('REPROGRAMADA', 'Reprogramada', 35);
    IF COLUMNPROPERTY(OBJECT_ID('dbo.VCT_PRM_ACCIONES_RESULTADOS'), 'ID', 'IsIdentity') = 1
        INSERT INTO dbo.VCT_PRM_ACCIONES_RESULTADOS (CODIGO, DESCRIPCION, ORDEN, ACTIVO, CARGA_MANUAL, FECHA_ALTA, USUARIO_ALTA)
        SELECT R.CODIGO, R.DESCRIPCION, R.ORDEN, 1, 1, GETDATE(), 'PASO5_1'
        FROM @R R WHERE NOT EXISTS (SELECT 1 FROM dbo.VCT_PRM_ACCIONES_RESULTADOS X WHERE X.CODIGO = R.CODIGO);
    ELSE
        INSERT INTO dbo.VCT_PRM_ACCIONES_RESULTADOS (ID, CODIGO, DESCRIPCION, ORDEN, ACTIVO, CARGA_MANUAL, FECHA_ALTA, USUARIO_ALTA)
        SELECT (SELECT ISNULL(MAX(ID), 0) FROM dbo.VCT_PRM_ACCIONES_RESULTADOS) + ROW_NUMBER() OVER (ORDER BY R.ORDEN),
               R.CODIGO, R.DESCRIPCION, R.ORDEN, 1, 1, GETDATE(), 'PASO5_1'
        FROM @R R WHERE NOT EXISTS (SELECT 1 FROM dbo.VCT_PRM_ACCIONES_RESULTADOS X WHERE X.CODIGO = R.CODIGO);
    PRINT 'OK   resultados nuevos (' + CONVERT(VARCHAR(10), @@ROWCOUNT) + ' agregados).';

    /* 2.4 tipos sin subtipos y sin acciones: se desactivan (no se borran) */
    UPDATE T SET ACTIVO = 0, FECHA_UPD = GETDATE(), USUARIO_UPD = 'PASO5_1'
    FROM dbo.VCT_PRM_ACCIONES_TIPOS T
    WHERE T.CODIGO IN ('APROBACION','VIATICO','HONORARIO') AND T.ACTIVO = 1
      AND NOT EXISTS (SELECT 1 FROM dbo.VCT_PRM_ACCIONES_SUBTIPOS S WHERE S.ID_TIPO = T.ID AND S.ACTIVO = 1)
      AND NOT EXISTS (SELECT 1 FROM dbo.VCT_ACCIONES A WHERE A.ID_TIPO = T.ID)
      AND NOT EXISTS (SELECT 1 FROM dbo.VCT_PRM_ACCIONES_REGLAS G WHERE G.ID_TIPO = T.ID);
    PRINT 'OK   tipos sin uso desactivados (' + CONVERT(VARCHAR(10), @@ROWCOUNT) + ').';

    COMMIT;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    PRINT 'FALLO PASO5_1: ' + ERROR_MESSAGE();
END CATCH;
GO

IF EXISTS (SELECT 1 FROM #TRG51 WHERE ON_ = 1) ENABLE TRIGGER TR_VCT_AUDITORIA_DDL ON DATABASE;
DROP TABLE #TRG51;

/* resultado: como queda la tipificacion */
SELECT T.CODIGO AS TIPO, T.ACTIVO AS TIPO_ACTIVO, S.CODIGO AS SUBTIPO, S.DESCRIPCION, S.CARGA_MANUAL, S.ACTIVO
FROM dbo.VCT_PRM_ACCIONES_TIPOS T LEFT JOIN dbo.VCT_PRM_ACCIONES_SUBTIPOS S ON S.ID_TIPO = T.ID
ORDER BY T.ORDEN, S.ORDEN;
SELECT CODIGO, DESCRIPCION, ORDEN, CARGA_MANUAL, ACTIVO FROM dbo.VCT_PRM_ACCIONES_RESULTADOS ORDER BY ORDEN, ID;
/* acciones cargadas con tipo y sin subtipo (solo para revisar; este script no las modifica) */
SELECT A.ID, T.CODIGO AS TIPO, A.ORIGEN, A.TITULO, A.ID_PROYECTO, A.FECHA_CREACION
FROM dbo.VCT_ACCIONES A LEFT JOIN dbo.VCT_PRM_ACCIONES_TIPOS T ON T.ID = A.ID_TIPO
WHERE A.ID_SUBTIPO IS NULL ORDER BY A.ID;
PRINT 'OK   PASO5_1 terminado.';
