/* TMP_REINICIAR_1347 - arreglo temporal para volver a probar "Iniciar proyecto" en el 1347.
   - Proyecto 1347 vuelve a Confirmado y sin fecha de inicio real.
   - Se borran sus registros de inicio (VCT_PROYECTOS_DOCUMENTOS TIPO 'INICIO').
   - NO toca la accion "Carga del plan" del consultor: al iniciar de nuevo, la regla
     PROYECTO_INICIADO ve que ya existe (no cancelada) y no la vuelve a generar.
   Muestra el antes y el despues, y los triggers de VCT_PROYECTOS (por si algo lo pasa a En curso). */
USE [MuhlePROD];
SET NOCOUNT ON;
DECLARE @P INT, @CONF INT;
SELECT @P = ID FROM dbo.VCT_PROYECTOS WHERE CODIGO = '1347';
SELECT @CONF = ID FROM dbo.VCT_PRM_PROYECTOS_ESTADOS WHERE CODIGO = 'CONFIRMADO';

SELECT 'ANTES' AS MOMENTO, P.ID, P.CODIGO, E.CODIGO AS ESTADO, P.FECHA_INICIO_REAL,
       (SELECT COUNT(*) FROM dbo.VCT_PROYECTOS_DOCUMENTOS D WHERE D.ID_PROYECTO = P.ID AND D.TIPO = 'INICIO') AS INICIOS
FROM dbo.VCT_PROYECTOS P LEFT JOIN dbo.VCT_PRM_PROYECTOS_ESTADOS E ON E.ID = P.ID_ESTADO WHERE P.ID = @P;

BEGIN TRAN;
    DELETE FROM dbo.VCT_PROYECTOS_DOCUMENTOS WHERE ID_PROYECTO = @P AND TIPO = 'INICIO';
    UPDATE dbo.VCT_PROYECTOS SET ID_ESTADO = @CONF, FECHA_INICIO_REAL = NULL, FECHA_UPD = GETDATE(), USUARIO_UPD = 'TMP_REINICIAR'
    WHERE ID = @P;
COMMIT;

SELECT 'DESPUES' AS MOMENTO, P.ID, P.CODIGO, E.CODIGO AS ESTADO, P.FECHA_INICIO_REAL,
       (SELECT COUNT(*) FROM dbo.VCT_PROYECTOS_DOCUMENTOS D WHERE D.ID_PROYECTO = P.ID AND D.TIPO = 'INICIO') AS INICIOS
FROM dbo.VCT_PROYECTOS P LEFT JOIN dbo.VCT_PRM_PROYECTOS_ESTADOS E ON E.ID = P.ID_ESTADO WHERE P.ID = @P;

/* accion de carga del plan (no se duplica al reiniciar mientras no este cancelada) */
SELECT A.ID, A.TITULO, ES.CODIGO AS ESTADO, A.FECHA_CREACION, A.FECHA_VENCIMIENTO
FROM dbo.VCT_ACCIONES A
INNER JOIN dbo.VCT_PRM_ACCIONES_REGLAS R ON R.ID = A.ID_REGLA_ORIGEN AND R.CODIGO_EVENTO = 'PROYECTO_INICIADO'
LEFT JOIN dbo.VCT_PRM_ACCIONES_ESTADOS ES ON ES.ID = A.ID_ESTADO
WHERE A.ID_PROYECTO = @P;

/* triggers sobre VCT_PROYECTOS */
SELECT T.name, T.is_disabled FROM sys.triggers T WHERE T.parent_id = OBJECT_ID('dbo.VCT_PROYECTOS');
