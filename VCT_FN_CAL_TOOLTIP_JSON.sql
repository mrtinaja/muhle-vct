/* TT42: enriquece JSON de lectura conservando todos sus campos y valores.
   SQL Server 2017, compatibilidad >=130. No escribe registros de negocio. */
USE [MuhlePROD];
GO
CREATE OR ALTER FUNCTION dbo.VCT_FN_CAL_TOOLTIP_JSON
(@DATA VARCHAR(MAX), @CONS INT, @PROY INT)
RETURNS VARCHAR(MAX)
AS
BEGIN
 DECLARE @JSON NVARCHAR(MAX)=CONVERT(NVARCHAR(MAX),@DATA);
 IF ISJSON(@JSON)<>1
   SET @JSON=REPLACE(REPLACE(REPLACE(@JSON,N'&quot;',N'"'),N'&lt;',N'<'),N'&amp;',N'&');
 IF ISJSON(@JSON)<>1 RETURN @DATA;
 DECLARE @ITEMS TABLE(N INT PRIMARY KEY,J NVARCHAR(MAX),F DATE);
 INSERT INTO @ITEMS(N,J,F)
 SELECT CONVERT(INT,[key]),value,TRY_CONVERT(DATE,JSON_VALUE(value,'$.f'),120)
 FROM OPENJSON(@JSON) WHERE type=5;
 IF NOT EXISTS(SELECT 1 FROM @ITEMS) RETURN @DATA;
 DECLARE @FROM DATE,@TO DATE,@CTX NVARCHAR(MAX)=N'[]',@I INT=-1,@NEXT INT,
 @OBJ NVARCHAR(MAX),@DAY DATE,@R NVARCHAR(320),@RI NVARCHAR(10),
 @CLI NVARCHAR(500),@P NVARCHAR(1000),@S NVARCHAR(MAX),
 @PCLI NVARCHAR(500),@PNAME NVARCHAR(1000),@PSRV NVARCHAR(MAX),
 @RESULT NVARCHAR(MAX)=N'[',@SEP NVARCHAR(1)=N'';
 SELECT @FROM=MIN(F),@TO=MAX(F) FROM @ITEMS;
 IF @CONS IS NOT NULL
 BEGIN
   IF @FROM IS NOT NULL AND @TO IS NOT NULL
     SET @CTX=CONVERT(NVARCHAR(MAX),dbo.VCT_FN_AGENDA_DIAS_JSON(@CONS,@FROM,@TO));
   SELECT @R=LTRIM(RTRIM(ISNULL(APELLIDOS,'')+CASE WHEN NULLIF(LTRIM(RTRIM(APELLIDOS)),'') IS NOT NULL AND NULLIF(LTRIM(RTRIM(NOMBRES)),'') IS NOT NULL THEN ', ' ELSE '' END+ISNULL(NOMBRES,''))),
     @RI=UPPER(LEFT(LTRIM(ISNULL(NOMBRES,'')),1)+LEFT(LTRIM(ISNULL(APELLIDOS,'')),1))
   FROM dbo.VCT_CONSULTORES WHERE ID=@CONS;
 END;
 IF @PROY IS NOT NULL
 BEGIN
   SELECT @PCLI=C.RAZON_SOCIAL,
     @PNAME=ISNULL('('+NULLIF(LTRIM(RTRIM(P.CODIGO)),'')+') ','')+ISNULL(P.NOMBRE,'')
   FROM dbo.VCT_PROYECTOS P LEFT JOIN dbo.VCT_CLIENTES C ON C.ID=P.IDCLIENTE
   WHERE P.ID=@PROY;
   SELECT @PSRV=STUFF((SELECT ', '+UPPER(LEFT(ISNULL(S.CODIGO,''),2))+'|'+ISNULL(CONVERT(VARCHAR(200),S.DESCRIPCION),'')
     FROM dbo.VCT_PROYECTOS_SERVICIOS PS
     JOIN dbo.VCT_PRM_SERVICIOS S ON S.ID=PS.ID_SERVICIO
     WHERE PS.ID_PROYECTO=@PROY ORDER BY S.ID
     FOR XML PATH(''),TYPE).value('.','NVARCHAR(MAX)'),1,2,'');
 END;
 WHILE 1=1
 BEGIN
   SET @NEXT=NULL; SELECT @NEXT=MIN(N) FROM @ITEMS WHERE N>@I;
   IF @NEXT IS NULL BREAK;
   SELECT @OBJ=J,@DAY=F FROM @ITEMS WHERE N=@NEXT;
   SELECT @CLI=@PCLI,@P=@PNAME,@S=@PSRV;
   IF @CONS IS NOT NULL AND JSON_VALUE(@OBJ,'$.e')='ASIGNADO'
     SELECT TOP 1 @CLI=JSON_VALUE(value,'$.cli'),@P=JSON_VALUE(value,'$.proy'),@S=JSON_VALUE(value,'$.srv')
     FROM OPENJSON(@CTX) WHERE JSON_VALUE(value,'$.f')=CONVERT(VARCHAR(10),@DAY,120);
   IF NULLIF(JSON_VALUE(@OBJ,'$.cli'),'') IS NULL AND NULLIF(@CLI,'') IS NOT NULL SET @OBJ=JSON_MODIFY(@OBJ,'$.cli',@CLI);
   IF NULLIF(JSON_VALUE(@OBJ,'$.proy'),'') IS NULL AND NULLIF(@P,'') IS NOT NULL SET @OBJ=JSON_MODIFY(@OBJ,'$.proy',@P);
   IF NULLIF(JSON_VALUE(@OBJ,'$.srv'),'') IS NULL AND NULLIF(@S,'') IS NOT NULL SET @OBJ=JSON_MODIFY(@OBJ,'$.srv',@S);
   IF NULLIF(JSON_VALUE(@OBJ,'$.r'),'') IS NULL AND NULLIF(@R,'') IS NOT NULL SET @OBJ=JSON_MODIFY(@OBJ,'$.r',@R);
   IF NULLIF(JSON_VALUE(@OBJ,'$.ri'),'') IS NULL AND NULLIF(@RI,'') IS NOT NULL SET @OBJ=JSON_MODIFY(@OBJ,'$.ri',@RI);
   SET @RESULT=@RESULT+@SEP+@OBJ; SET @SEP=N','; SET @I=@NEXT;
 END;
 RETURN CONVERT(VARCHAR(MAX),@RESULT+N']');
END;
GO
