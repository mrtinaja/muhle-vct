/* CIERRE_CAL_V12. Protecciones en ambos sentidos, por conjuntos de filas.
 No elimina ni corrige conflictos anteriores. No se ejecutan INSERT de prueba.
 Cinco triggers: disponibilidad, actividades, asignaciones, fechas de visita y horas.
 Reejecutable. Instalacion atomica de estos cinco triggers.
*/
USE [MuhlePROD];
GO
SET NOCOUNT ON; SET XACT_ABORT ON; SET ANSI_NULLS ON; SET QUOTED_IDENTIFIER ON;
BEGIN TRY
 BEGIN TRANSACTION;
 IF COL_LENGTH('dbo.VCT_PRM_AGENDA_CONSULTOR','ID_CONSULTOR') IS NULL THROW 51012, 'Falta dbo.VCT_PRM_AGENDA_CONSULTOR.ID_CONSULTOR. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PRM_AGENDA_CONSULTOR','FECHA') IS NULL THROW 51012, 'Falta dbo.VCT_PRM_AGENDA_CONSULTOR.FECHA. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PRM_AGENDA_CONSULTOR','TIPO') IS NULL THROW 51012, 'Falta dbo.VCT_PRM_AGENDA_CONSULTOR.TIPO. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_AGENDA_CONSULTOR_ACTIVIDAD','ID_CONSULTOR') IS NULL THROW 51012, 'Falta dbo.VCT_AGENDA_CONSULTOR_ACTIVIDAD.ID_CONSULTOR. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_AGENDA_CONSULTOR_ACTIVIDAD','FECHA') IS NULL THROW 51012, 'Falta dbo.VCT_AGENDA_CONSULTOR_ACTIVIDAD.FECHA. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_AGENDA_CONSULTOR_ACTIVIDAD','ACTIVO') IS NULL THROW 51012, 'Falta dbo.VCT_AGENDA_CONSULTOR_ACTIVIDAD.ACTIVO. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PROYECTOS_VISITAS','ID') IS NULL THROW 51012, 'Falta dbo.VCT_PROYECTOS_VISITAS.ID. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PROYECTOS_VISITAS','FECHA_DESDE') IS NULL THROW 51012, 'Falta dbo.VCT_PROYECTOS_VISITAS.FECHA_DESDE. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PROYECTOS_VISITAS','FECHA_HASTA') IS NULL THROW 51012, 'Falta dbo.VCT_PROYECTOS_VISITAS.FECHA_HASTA. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PROYECTOS_VISITAS','ESTADO') IS NULL THROW 51012, 'Falta dbo.VCT_PROYECTOS_VISITAS.ESTADO. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PROYECTOS_VISITAS_CONSULTORES','ID_VISITA') IS NULL THROW 51012, 'Falta dbo.VCT_PROYECTOS_VISITAS_CONSULTORES.ID_VISITA. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PROYECTOS_VISITAS_CONSULTORES','ID_CONSULTOR') IS NULL THROW 51012, 'Falta dbo.VCT_PROYECTOS_VISITAS_CONSULTORES.ID_CONSULTOR. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PROYECTOS_VISITAS_REGISTRO','ID_CONSULTOR') IS NULL THROW 51012, 'Falta dbo.VCT_PROYECTOS_VISITAS_REGISTRO.ID_CONSULTOR. Sin instalar bloqueos.', 1;
 IF COL_LENGTH('dbo.VCT_PROYECTOS_VISITAS_REGISTRO','FECHA') IS NULL THROW 51012, 'Falta dbo.VCT_PROYECTOS_VISITAS_REGISTRO.FECHA. Sin instalar bloqueos.', 1;
 EXEC sys.sp_executesql N'CREATE OR ALTER TRIGGER dbo.VCT_CIERRE12_DISPONIBILIDAD ON dbo.VCT_PRM_AGENDA_CONSULTOR AFTER INSERT, UPDATE AS BEGIN SET NOCOUNT ON; SET XACT_ABORT ON;
 IF EXISTS(SELECT 1 FROM inserted I JOIN deleted O ON O.ID_CONSULTOR=I.ID_CONSULTOR AND O.FECHA=I.FECHA
  WHERE O.TIPO=''LICENCIA'' AND ISNULL(I.TIPO,'''')<>''LICENCIA'')
  THROW 51012, ''Elimine primero la licencia o vacaciones antes de cambiar el tipo del dia.'', 1;
 IF EXISTS(SELECT 1 FROM inserted D JOIN dbo.VCT_AGENDA_CONSULTOR_ACTIVIDAD A WITH(UPDLOCK,HOLDLOCK)
  ON A.ID_CONSULTOR=D.ID_CONSULTOR AND A.FECHA=D.FECHA WHERE D.TIPO=''LICENCIA'' AND A.ACTIVO=1)
  THROW 51012, ''El dia tiene actividades. Reprograme las actividades antes de cargar la licencia.'', 1;
 IF EXISTS(SELECT 1 FROM inserted D JOIN dbo.VCT_PROYECTOS_VISITAS_CONSULTORES C WITH(UPDLOCK,HOLDLOCK)
  ON C.ID_CONSULTOR=D.ID_CONSULTOR JOIN dbo.VCT_PROYECTOS_VISITAS V WITH(UPDLOCK,HOLDLOCK) ON V.ID=C.ID_VISITA
  WHERE D.TIPO=''LICENCIA'' AND D.FECHA BETWEEN CONVERT(DATE,V.FECHA_DESDE) AND CONVERT(DATE,ISNULL(V.FECHA_HASTA,V.FECHA_DESDE)) AND ISNULL(V.ESTADO,'''') NOT IN (''CANCELADO'',''CANCELADA'',''ANULADO'',''ANULADA''))
  THROW 51012, ''El dia tiene una visita asignada. Reprograme la visita antes de cargar la licencia.'', 1;
 IF EXISTS(SELECT 1 FROM inserted D JOIN dbo.VCT_PROYECTOS_VISITAS_REGISTRO R WITH(UPDLOCK,HOLDLOCK)
  ON R.ID_CONSULTOR=D.ID_CONSULTOR AND R.FECHA=D.FECHA WHERE D.TIPO=''LICENCIA'')
  THROW 51012, ''El dia tiene horas registradas. Revise el registro antes de cargar la licencia.'', 1;
END;';
 EXEC sys.sp_executesql N'CREATE OR ALTER TRIGGER dbo.VCT_CIERRE12_ACTIVIDADES ON dbo.VCT_AGENDA_CONSULTOR_ACTIVIDAD AFTER INSERT, UPDATE AS BEGIN SET NOCOUNT ON; SET XACT_ABORT ON;
 IF EXISTS(SELECT 1 FROM inserted I JOIN dbo.VCT_PRM_AGENDA_CONSULTOR D WITH(UPDLOCK,HOLDLOCK)
  ON D.ID_CONSULTOR=I.ID_CONSULTOR AND D.FECHA=I.FECHA WHERE I.ACTIVO=1 AND D.TIPO=''LICENCIA'')
  THROW 51012, ''El consultor tiene licencia o vacaciones. Elimine primero la licencia para cargar actividades.'', 1;
END;';
 EXEC sys.sp_executesql N'CREATE OR ALTER TRIGGER dbo.VCT_CIERRE12_ASIGNACIONES ON dbo.VCT_PROYECTOS_VISITAS_CONSULTORES AFTER INSERT, UPDATE AS BEGIN SET NOCOUNT ON; SET XACT_ABORT ON;
 IF EXISTS(SELECT 1 FROM inserted I JOIN dbo.VCT_PROYECTOS_VISITAS V ON V.ID=I.ID_VISITA
  JOIN dbo.VCT_PRM_AGENDA_CONSULTOR D WITH(UPDLOCK,HOLDLOCK) ON D.ID_CONSULTOR=I.ID_CONSULTOR
  WHERE D.TIPO=''LICENCIA'' AND D.FECHA BETWEEN CONVERT(DATE,V.FECHA_DESDE) AND CONVERT(DATE,ISNULL(V.FECHA_HASTA,V.FECHA_DESDE)) AND ISNULL(V.ESTADO,'''') NOT IN (''CANCELADO'',''CANCELADA'',''ANULADO'',''ANULADA''))
  THROW 51012, ''La visita coincide con licencia o vacaciones del consultor. Elimine primero la licencia o reprograme la visita.'', 1;
END;';
 EXEC sys.sp_executesql N'CREATE OR ALTER TRIGGER dbo.VCT_CIERRE12_VISITAS ON dbo.VCT_PROYECTOS_VISITAS AFTER INSERT, UPDATE AS BEGIN SET NOCOUNT ON; SET XACT_ABORT ON;
 IF EXISTS(SELECT 1 FROM inserted V JOIN dbo.VCT_PROYECTOS_VISITAS_CONSULTORES C ON C.ID_VISITA=V.ID
  JOIN dbo.VCT_PRM_AGENDA_CONSULTOR D WITH(UPDLOCK,HOLDLOCK) ON D.ID_CONSULTOR=C.ID_CONSULTOR
  WHERE D.TIPO=''LICENCIA'' AND D.FECHA BETWEEN CONVERT(DATE,V.FECHA_DESDE) AND CONVERT(DATE,ISNULL(V.FECHA_HASTA,V.FECHA_DESDE)) AND ISNULL(V.ESTADO,'''') NOT IN (''CANCELADO'',''CANCELADA'',''ANULADO'',''ANULADA''))
  THROW 51012, ''La nueva fecha de visita coincide con licencia o vacaciones de un consultor asignado.'', 1;
END;';
 EXEC sys.sp_executesql N'CREATE OR ALTER TRIGGER dbo.VCT_CIERRE12_REGISTROS ON dbo.VCT_PROYECTOS_VISITAS_REGISTRO AFTER INSERT, UPDATE AS BEGIN SET NOCOUNT ON; SET XACT_ABORT ON;
 IF EXISTS(SELECT 1 FROM inserted I JOIN dbo.VCT_PRM_AGENDA_CONSULTOR D WITH(UPDLOCK,HOLDLOCK)
  ON D.ID_CONSULTOR=I.ID_CONSULTOR AND D.FECHA=I.FECHA WHERE D.TIPO=''LICENCIA'')
  THROW 51012, ''No se pueden registrar horas en un dia con licencia o vacaciones. Revise primero la licencia.'', 1;
END;';
 COMMIT TRANSACTION;
 PRINT 'CIERRE_CAL_V12: cinco bloqueos instalados. No se modificaron registros existentes.';
END TRY
BEGIN CATCH
 IF @@TRANCOUNT>0 ROLLBACK TRANSACTION;
 THROW;
END CATCH;
GO
