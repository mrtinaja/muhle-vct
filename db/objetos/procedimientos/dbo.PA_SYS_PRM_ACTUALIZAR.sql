IF (@LN_COUNT2 > @LN_COUNT1) BEGIN
	SET @LN_COUNT1 = @LN_COUNT2;
END;
UPDATE	PRM
SET	PRM_VAL = @LN_COUNT1
WHERE	(PRM_COD = 'PHYSICAL_CALL_KEY');
SELECT @LSOPERA = 'UPDATE', @LSTABLA = 'PRM', @LNFILAS_AFEC = @@ROWCOUNT, @LNERRORNUM = @@ERROR;
IF (@LNERRORNUM <> 0) GOTO FALLO;
 
