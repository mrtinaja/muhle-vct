SET @LN_COUNT2 = (SELECT ISNULL(MAX(CONVERT(NUMERIC(10, 0), SUBSTRING(PKEY_ATTENDED_CUSTOMER, 1, 10))) + 1, 1) FROM DSS_TBATTENDED_CUSTOMER WHERE (ISNUMERIC(SUBSTRING(PKEY_ATTENDED_CUSTOMER, 1, 10)) = 1 AND LEN(PKEY_ATTENDED_CUSTOMER) = 13));
-- EVALÚA EN DÓNDE ESTA LA ÚLTIMA PKEY GENERADA, ENTRE LA TABLA ACTUAL Y SU HISTÓRICA.
IF (@LN_COUNT2 > @LN_COUNT1) BEGIN
	SET @LN_COUNT1 = @LN_COUNT2;
END;
UPDATE	PRM
SET	PRM_VAL = @LN_COUNT1
WHERE	(PRM_COD = 'ATTENDED_CUSTOMER_KEY');
SELECT @LSOPERA = 'UPDATE', @LSTABLA = 'PRM', @LNFILAS_AFEC = @@ROWCOUNT, @LNERRORNUM = @@ERROR;
IF (@LNERRORNUM <> 0) GOTO FALLO;
 
SET @LN_COUNT1 = (SELECT ISNULL(MAX(CONVERT(NUMERIC(10, 0), SUBSTRING(PKEY, 1, 10))) + 1, 1) FROM PHYSICAL_CALL WHERE (ISNUMERIC(SUBSTRING(PKEY, 1, 10)) = 1 AND LEN(PKEY) = 13));
SET @LN_COUNT2 = (SELECT ISNULL(MAX(CONVERT(NUMERIC(10, 0), SUBSTRING(PKEY_PHYSICAL_CALL, 1, 10))) + 1, 1) FROM DSS_TBPHYSICAL_CALL WHERE (ISNUMERIC(SUBSTRING(PKEY_PHYSICAL_CALL, 1, 10)) = 1 AND LEN(PKEY_PHYSICAL_CALL) = 13));
